-- Registra automáticamente cada cambio de estado de los pedidos,
-- incluyendo el usuario y la fecha/hora del cambio.

CREATE TABLE IF NOT EXISTS public.pedido_estado_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INT NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  estado TEXT NOT NULL CHECK (
    estado IN ('PENDIENTE', 'APROBADO', 'EN_PREPARACION', 'LISTO', 'RECOGIDO', 'ENTREGADO', 'CANCELADO')
  ),
  cambiado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  cambiado_por UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  cambiado_por_nombre TEXT
);

CREATE INDEX IF NOT EXISTS pedido_estado_historial_pedido_fecha_idx
  ON public.pedido_estado_historial (pedido_id, cambiado_en);

ALTER TABLE public.pedido_estado_historial ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS pedido_estado_historial_read ON public.pedido_estado_historial;
CREATE POLICY pedido_estado_historial_read ON public.pedido_estado_historial
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.pedidos p
      WHERE p.id = pedido_id
    )
  );

GRANT SELECT ON public.pedido_estado_historial TO authenticated;

CREATE OR REPLACE FUNCTION public.registrar_cambio_estado_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_nombre TEXT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.estado IS NOT DISTINCT FROM OLD.estado THEN
    RETURN NEW;
  END IF;

  SELECT nombre_completo
    INTO v_nombre
    FROM public.perfiles_usuario
   WHERE usuario_id = auth.uid()
   LIMIT 1;

  INSERT INTO public.pedido_estado_historial (
    pedido_id,
    estado,
    cambiado_por,
    cambiado_por_nombre
  )
  VALUES (
    NEW.id,
    NEW.estado,
    auth.uid(),
    v_nombre
  );

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_cambio_estado_pedido() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.registrar_cambio_estado_pedido() TO authenticated;

DROP TRIGGER IF EXISTS pedidos_historial_estado_insert ON public.pedidos;
CREATE TRIGGER pedidos_historial_estado_insert
  AFTER INSERT ON public.pedidos
  FOR EACH ROW
  EXECUTE FUNCTION public.registrar_cambio_estado_pedido();

DROP TRIGGER IF EXISTS pedidos_historial_estado_update ON public.pedidos;
CREATE TRIGGER pedidos_historial_estado_update
  AFTER UPDATE OF estado ON public.pedidos
  FOR EACH ROW
  EXECUTE FUNCTION public.registrar_cambio_estado_pedido();

-- Los pedidos ya existentes reciben una marca inicial; los cambios
-- anteriores a esta migración no se pueden reconstruir.
INSERT INTO public.pedido_estado_historial (pedido_id, estado, cambiado_en)
SELECT p.id, p.estado, COALESCE(p.actualizado_en, p.creado_en, NOW())
  FROM public.pedidos p
 WHERE NOT EXISTS (
   SELECT 1
   FROM public.pedido_estado_historial h
   WHERE h.pedido_id = p.id
 );
